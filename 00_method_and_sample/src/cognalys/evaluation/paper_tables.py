#!/usr/bin/env python3
"""Every number in the paper's result tables, rebuilt from named runs.

The tables were assembled by hand from whichever artifacts were newest,
across runs made by different versions of the pipeline. Nothing could
regenerate them, so nothing could check them, and a later run silently
changed what "the latest artifact" meant.

Here the inputs are named explicitly -- a corpus, a list of run
directories, optionally a labelled worksheet -- and never discovered by
scanning `outputs/`. Every cell is derived by a function in this module,
every rate is printed with its numerator and denominator, and a rate whose
denominator is zero is `N/A` rather than 0%, because "nothing happened" and
"it happened 0% of the time" are different claims.

Each table is emitted twice: as LaTeX for the paper, and as rows carrying
the artifact every value was read from, so any cell can be traced by hand.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple


from cognalys.evaluation.coverage import coverage_report  # noqa: E402
from cognalys.evaluation.patch_correctness import tally as tally_correctness  # noqa: E402
from cognalys.utils.disposition import BUILD_VALIDATION_PASSING_STATUSES  # noqa: E402
from cognalys.validation.detector_replay import (  # noqa: E402
    NO_DETECTOR_COVERAGE, UNTRUSTED_STATES, reclassify as reclassify_replay,
)


def rate(numerator: int, denominator: int) -> str:
    """`n/d (p%)`, or `N/A` when there is nothing to divide by."""
    if not denominator:
        return "N/A"
    return f"{numerator}/{denominator} ({100 * numerator / denominator:.0f}%)"


_LATEX_SPECIAL = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
    "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def latex_escape(value: object) -> str:
    return "".join(_LATEX_SPECIAL.get(character, character)
                   for character in str(value))


def latex_table(caption: str, label: str, header: Sequence[str],
                rows: Iterable[Sequence[object]], note: str = "") -> str:
    """A self-contained table environment the paper can \\input."""
    columns = "l" + "r" * (len(header) - 1)
    lines = [
        "% Generated by scripts/generate_paper_results.py -- do not edit.",
        r"\begin{table}[t]", r"\centering", r"\small",
        rf"\caption{{{latex_escape(caption)}}}", rf"\label{{{label}}}",
        rf"\begin{{tabular}}{{{columns}}}", r"\hline",
        " & ".join(latex_escape(item) for item in header) + r" \\", r"\hline",
    ]
    for row in rows:
        lines.append(" & ".join(latex_escape(item) for item in row) + r" \\")
    lines += [r"\hline", r"\end{tabular}"]
    if note:
        lines.append(rf"\par\smallskip\footnotesize {latex_escape(note)}")
    lines.append(r"\end{table}")
    return "\n".join(lines) + "\n"


def _read_json(path: Path) -> Dict:
    try:
        value = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError, ValueError):
        return {}
    return value if isinstance(value, dict) else {}


def run_summary(name: str, run_dir: Path) -> Dict:
    """Everything a table needs from one run, with where it came from."""
    run_dir = Path(run_dir)
    retrospective_path = run_dir / "retrospective" / "retrospective.json"
    retrospective = _read_json(retrospective_path)
    findings = [
        item for item in retrospective.get("findings", []) or []
        if isinstance(item, dict)
    ]
    # Recomputed rather than read, so a run written before the coverage
    # section existed is reported on exactly the same terms as a new one.
    coverage = coverage_report(findings)
    execution_path = run_dir / "application_results" / "execution_report.json"
    execution = _read_json(execution_path)
    details = [
        item for item in execution.get("per_solution_details", []) or []
        if isinstance(item, dict)
    ]
    build_statuses: Dict[str, int] = {}
    regression: Dict[str, int] = {}
    replay: Dict[str, int] = {}
    for item in details:
        build = item.get("build_validation") or {}
        status = str(build.get("status", "") or "not_run")
        build_statuses[status] = build_statuses.get(status, 0) + 1
        suite = str((build.get("regression_tests") or {}).get("status", "")
                    or "not_run")
        regression[suite] = regression.get(suite, 0) + 1
        # Re-read under the current rules: runs recorded before detector
        # failures had their own state could credit a crashed scan.
        outcome = str(
            reclassify_replay(build.get("detector_replay") or {}).get("outcome", "")
            or "not_run"
        )
        replay[outcome] = replay.get(outcome, 0) + 1
    # Assessed afresh rather than read from the record, so runs validated
    # before the assessment existed are judged by the same rules.
    correctness = tally_correctness(
        item.get("build_validation") or {} for item in details
    )
    performance = (retrospective.get("llm_performance") or {}).get(
        "per_stage", {}
    ) or {}
    calls = sum(int(entry.get("calls", 0) or 0) for entry in performance.values())
    cache_hits = sum(
        int(entry.get("cache_hits", 0) or 0) for entry in performance.values()
    )
    # Answered by the finding's own identical earlier call: counted among the
    # calls like a cache hit, and like one never sent to the model.
    replays = sum(
        int(entry.get("replays", 0) or 0) for entry in performance.values()
    )
    # Shared research requests answered from the research corpus: likewise
    # counted among the calls and not sent.
    corpus_hits = sum(int(entry.get("corpus_hits", 0) or 0) for entry in performance.values())
    minutes = sum(
        int(entry.get("latency_ms", 0) or 0) for entry in performance.values()
    ) / 60000
    return {
        "name": name,
        "run_dir": str(run_dir),
        "run_id": str(retrospective.get("run_id", run_dir.name)),
        "pipeline": retrospective.get("pipeline", {}),
        "sources": {
            "retrospective": str(retrospective_path)
            if retrospective_path.is_file() else "",
            "execution_report": str(execution_path)
            if execution_path.is_file() else "",
        },
        "coverage": coverage,
        "funnel": retrospective.get("funnel", {}),
        "solutions_validated": len(details),
        "build_statuses": build_statuses,
        "regression_tests": regression,
        "detector_replay": replay,
        "patch_correctness": correctness,
        "model_calls": calls,
        "model_cache_hits": cache_hits,
        "model_replays": replays,
        "model_corpus_hits": corpus_hits,
        "model_minutes": round(minutes, 1),
    }


def cohort_table(lineage: Dict) -> Tuple[str, List[Dict]]:
    totals = lineage.get("totals", {})
    widest = totals.get("widest_shared_finding") or {}
    rows = [
        ("Observations in the corpus", totals.get("observations", 0)),
        ("Distinct findings", totals.get("findings", 0)),
        ("  of which in the corpus", totals.get("findings_in_corpus", 0)),
        ("Findings shared by several APKs",
         totals.get("findings_shared_by_several_apks", 0)),
        ("  widest: APKs reporting one finding", widest.get("apk_count", 0)),
        ("Findings adjudicated in the named runs",
         totals.get("findings_adjudicated", 0)),
        ("Findings with a patch", totals.get("findings_with_a_patch", 0)),
        ("Findings published", totals.get("findings_published", 0)),
    ]
    latex = latex_table(
        "Cohort lineage: from detector observations to published patches.",
        "tab:cohort-lineage", ("Measure", "Count"), rows,
        note=("A finding reported by several APKs that bundle the same "
              "library is counted once; those APKs are not independent "
              "replications."),
    )
    return latex, [
        {"measure": label, "value": value, "source": lineage.get("corpus", "")}
        for label, value in rows
    ]


def funnel_table(runs: Sequence[Dict]) -> Tuple[str, List[Dict]]:
    header = ("Condition", "Findings", "Patch proposed", "Abstained",
              "Classified", "Awaiting policy", "Invalid", "Published")
    rows, records = [], []
    for run in runs:
        coverage = run["coverage"]
        total = coverage["findings_attributed"]
        actions = coverage["actions"]
        row = (
            run["name"], total,
            rate(coverage["proposals"], total),
            rate(coverage["abstentions"], total),
            rate(actions.get("classify_no_change", 0), total),
            rate(actions.get("await_policy", 0), total),
            rate(actions.get("invalid", 0), total),
            rate(coverage["published"], total),
        )
        rows.append(row)
        records.append({
            **dict(zip(header, row)),
            "source": run["sources"]["retrospective"],
        })
    latex = latex_table(
        "What each condition did with the findings it was given.",
        "tab:funnel", header, rows,
        note=("Every rate is over the findings attributed to that run. "
              "Invalid means the decision was empty or unrecognised; it is "
              "never counted as a proposal."),
    )
    return latex, records


def decision_table(score: Optional[Dict]) -> Tuple[str, List[Dict]]:
    """Against the reviewer labels, or a stated absence of them."""
    if not score or not score.get("measured"):
        rows = [("Labelled findings with a decision", "0"),
                ("Status", "unmeasured: no reviewer labels")]
        latex = latex_table(
            "Decision quality against independent labels.",
            "tab:decision-quality", ("Measure", "Value"), rows,
            note=("No reviewer labels were available when this table was "
                  "generated. Decision quality is not reported."),
        )
        return latex, [{"measure": label, "value": value} for label, value in rows]
    counts = score["counts"]
    measured = score["measured"]
    rows = [
        ("Agreed with reviewer", rate(counts["agreed"], measured)),
        ("Avoidable abstention", rate(counts["avoidable_abstention"], measured)),
        ("Unwarranted action", rate(counts["unwarranted_action"], measured)),
        ("Different action", rate(counts["different_action"], measured)),
        ("Undecided", rate(counts["undecided"], measured)),
        ("Not labelled", str(counts["not_labelled"])),
        ("Never adjudicated", str(counts["not_adjudicated"])),
    ]
    latex = latex_table(
        "Decision quality against independent labels.",
        "tab:decision-quality", ("Outcome", "Findings"), rows,
        note=("Avoidable abstention: the reviewer judged a repair "
              "appropriate and none was produced. Unwarranted action: the "
              "reviewer judged no change appropriate and one was produced."),
    )
    return latex, [{"measure": label, "value": value} for label, value in rows]


def validation_table(runs: Sequence[Dict]) -> Tuple[str, List[Dict]]:
    header = ("Condition", "Validated", "Build passed", "Regression suite passed",
              "No tests executed", "Detector: repaired", "Detector: not replayable",
              "Correct (all evidence)", "Incorrect")
    rows, records = [], []
    passing = BUILD_VALIDATION_PASSING_STATUSES
    for run in runs:
        total = run["solutions_validated"]
        built = sum(count for status, count in run["build_statuses"].items()
                    if status in passing)
        replay = run["detector_replay"]
        verdicts = (run.get("patch_correctness") or {}).get("verdicts", {})
        not_replayable = sum(
            replay.get(key, 0) for key in
            ("not_applicable", "not_run", NO_DETECTOR_COVERAGE, *UNTRUSTED_STATES)
        )
        row = (
            run["name"], total, rate(built, total),
            rate(run["regression_tests"].get("passed", 0), total),
            rate(run["regression_tests"].get("no_tests_executed", 0), total),
            rate(replay.get("repaired", 0), total),
            rate(not_replayable, total),
            rate(verdicts.get("correct", 0), total),
            rate(verdicts.get("incorrect", 0), total),
        )
        rows.append(row)
        records.append({**dict(zip(header, row)),
                        "source": run["sources"]["execution_report"]})
    latex = latex_table(
        "Executable evidence, kept apart by kind.",
        "tab:validation", header, rows,
        note=("A build that passes shows the patch compiles, not that the "
              "problem is gone. The detector column counts only findings "
              "whose reporting detector could be re-run on both revisions. Correct "
              "requires the violation reproduced and eliminated, a build not "
              "failed by the patch and a passing regression suite "
              "(evaluation.patch_correctness); every other patch is "
              "unverified, incorrect or an environment failure."),
    )
    return latex, records


def cost_table(runs: Sequence[Dict]) -> Tuple[str, List[Dict]]:
    # The research corpus column and sentence appear only when some run was
    # served from it, so a table of runs without one is unchanged.
    with_corpus = any(int(run.get("model_corpus_hits", 0) or 0) > 0 for run in runs)
    header = ("Condition", "Model calls", "Cache hits", "Replays",
              *(("Research corpus",) if with_corpus else ()),
              "Model minutes", "Minutes per finding")
    rows, records = [], []
    for run in runs:
        total = run["coverage"]["findings_attributed"]
        per_finding = (
            f"{run['model_minutes'] / total:.1f}" if total else "N/A"
        )
        row = (run["name"], run["model_calls"], run["model_cache_hits"],
               run.get("model_replays", 0),
               *((run.get("model_corpus_hits", 0),) if with_corpus else ()),
               f"{run['model_minutes']:.1f}", per_finding)
        rows.append(row)
        records.append({**dict(zip(header, row)),
                        "source": run["sources"]["retrospective"]})
    note = ("Cache hits and replays (a finding's identical request answered "
            "by its own earlier call) are counted among the model calls but "
            "were not sent to the model, and are reported separately.")
    if with_corpus:
        note += (" Research corpus: shared research requests answered from the research "
                 "corpus (an answer kept from an earlier run), likewise counted among the "
                 "model calls and not sent.")
    latex = latex_table("Model cost per condition.", "tab:cost", header, rows, note=note)
    return latex, records
